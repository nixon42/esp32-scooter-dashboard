static inline const uint8_t* boot_logo_get_bitmap(int logo_id)
{
    switch (logo_id) {
        case 1:  return s_logo_android;
        case 2:  return s_logo_espressif;
        case 3:  return s_logo_linux;
        case 4:  return s_logo_arch;
        case 0:
        default: return s_logo_vario;
    }
}

static inline const char* boot_logo_get_title(int logo_id)
{
    switch (logo_id) {
        case 1:  return "Android OS";
        case 2:  return "ESP32-C3";
        case 3:  return "Linux 5.15";
        case 4:  return "Arch Linux";
        case 0:
        default: return "Vario 125";
    }
}
